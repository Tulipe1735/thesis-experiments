class Robot(SavedInitialRobot):
    def __init__(self, *args, **kwargs):
        self.kernel = None
        super().__init__(*args, **kwargs)
        self.kernel = NativeControl(NATIVE, self.names, float(self.model.opt.timestep))

    def _controller(self):
        super()._controller()
        self.data.ctrl[:] = self.kernel.step(self.data.qpos[self.qids], self.data.qvel[self.vids], self.data.ctrl)


class EnvironmentPort(CountedPort):
    """Registered sensor faults are generated by the test environment, without truth labels."""
    def __init__(self, robot, fault, folder):
        super().__init__(robot)
        self.fault, self.folder = fault, folder

    def observe(self):
        observation = super().observe()
        if self.fault == 'missing_red_marker':
            rgb = np.asarray(Image.open(observation['head_rgb_path']).convert('RGB')).copy()
            red = (rgb[..., 0].astype(float) > 1.5 * rgb[..., 1]) & (rgb[..., 0].astype(float) > 1.5 * rgb[..., 2])
            rgb[red] = 0
            path = self.folder / (observation['observation_id'] + '_public_sensor_fault.png')
            Image.fromarray(rgb).save(path)
            observation['head_rgb_path'] = str(path)
        elif self.fault == 'invalid_depth':
            depth = np.load(observation['depth_path'], allow_pickle=False)
            path = self.folder / (observation['observation_id'] + '_public_depth_dropout.npy')
            np.save(path, np.full_like(depth, np.nan))
            observation['depth_path'] = str(path)
        return observation


class Execution:
    def __init__(self, context, policy, output, emit):
        self.context, self.policy, self.output, self.emit = context, policy, output, emit
        self.folder = output / 'episode'
        self.folder.mkdir(exist_ok=False)
        self.robot = self.port = self.skills = None
        self.error = None
        self.failed_tool = None
        self.calls = 0
        self.started = time.monotonic()

    def event(self, stage, event):
        self.emit(dict(stage=stage, event=event,
                  simulation_seconds=float(self.robot.data.time) if self.robot else 0.))

    def call(self, tool):
        self.event(tool, 'started')
        self.calls += 1
        result = getattr(self.skills, tool)()
        append_event(self.output / 'public_tools.jsonl', dict(tool=tool, result=result,
                     simulation_seconds=float(self.robot.data.time)))
        self.event(tool, 'completed')
        return result

    def run(self):
        case = self.context['case']
        write_new(self.folder / 'instance.json', case['instance'])
        write_new(self.folder / 'run_config.json', dict(date='2026-10-29', task='T01', boundary='simulation',
            driver='ROS2 ExecuteSkill Action', policy_reads_object_truth=False, spectator_used_by_policy=False,
            model_requests=0, target_count=1, split=case['evaluation_role']))
        self.robot = Robot(self.folder, case['instance'], initial_state=ROOT / case['initial_source'],
                           scene_path=ROOT / self.context['model']['path'], budget=180.)
        self.port = EnvironmentPort(self.robot, self.context.get('fault'), self.folder)
        self.skills = RevisionSkills(self.port, self.folder, gain=self.policy.get('gain', .5))
        public_result = dict(execution_status='FAILED', runtime_check='NOT_EVALUATED', reason='execution has not completed')
        try:
            self.event('precondition', 'started')
            observation = self.port.observe()
            tray = locate_tray(observation)
            if len(visible_cups(observation, 1)) != 1:
                raise ValueError('Exactly one compatible visible cup is required')
            self.event('precondition', 'passed')
            self.robot.advance(.75, 'initial_settling')
            for tool in ['inspect_scene', 'grasp_cup', 'transfer_to_tray']:
                self.failed_tool = tool
                self.call(tool)
            if self.policy['guard']:
                self.failed_tool = 'inspect_alignment'
                decision = self.call('inspect_alignment')
                if decision['status'] == 'CORRECT':
                    self.failed_tool = 'correct_alignment'
                    self.call('correct_alignment')
            self.failed_tool = 'release_in_tray'
            self.call('release_in_tray')
            self.failed_tool = None
            # The private environment schedules a disturbance; policy never sees its labels or state.
            if self.context.get('fault') in ('post_force_left', 'post_force_right'):
                force = 5. if self.context['fault'] == 'post_force_left' else -5.
                body = self.robot.model.body('task_cup').id
                self.robot.data.xfrc_applied[body, 1] = force
                self.robot.advance(.10, 'registered_external_disturbance')
                self.robot.data.xfrc_applied[body] = 0.
                write_new(self.output / 'environment_disturbance.json', dict(force_N=[0., force, 0.],
                          duration_s=.10, trigger='placement_motion_completed', policy_access=False))
            self.event('postcondition', 'started')
            samples = []
            for index in range(3):
                if index:
                    self.port.invoke('wait', dict(seconds=.5))
                observation = self.port.observe()
                try:
                    sample = observe_evidence(observation)
                except Exception as error:
                    sample = dict(observation_id=observation['observation_id'],
                                  simulation_seconds=observation['simulation_seconds'], error=str(error))
                samples.append(sample)
            check = verdict(samples)
            write_new(self.output / 'runtime_verification.json', check)
            public_result = dict(execution_status='COMPLETED', runtime_check=check['status'], reason=check['reason'])
            self.event('postcondition', check['status'])
        except Exception as error:
            self.error = dict(type=type(error).__name__, message=str(error))
            precondition = self.robot.kernel.steps == 0
            public_result = dict(execution_status='REJECTED' if precondition else 'FAILED',
                                 runtime_check='NOT_EVALUATED', reason=str(error))
            self.event(self.failed_tool or 'precondition', public_result['execution_status'])
        finally:
            # The runtime result is sealed before independent private evaluation.
            write_new(self.output / 'public_result.json', public_result)
            self.robot.finish()
        kernel = self.robot.kernel.summary()
        from experiments.t0_agent_v1.tray_verify import verify
        independent = verify(self.folder, execution_error=self.error)
        result = dict(case_id=case['id'], policy=self.policy, runtime_result=public_result,
            independent_success=independent['verified_success'], initial_valid=independent['initial_valid'],
            terminal_stable_s=independent['terminal_simultaneous_stable_s'],
            failed_tool=self.failed_tool, execution_error=self.error,
            physical_episodes=int(self.robot.kernel.steps > 0), physics_steps=self.robot.kernel.steps,
            simulation_seconds=float(self.robot.data.time), low_level_command_calls=self.port.command_calls,
            high_level_tool_calls=self.calls, kernel=kernel, model_requests=0,
            weight_updates=0, episode=relative(self.folder), wall_seconds=time.monotonic()-self.started,
            initial_sha256=sha(self.folder / 'initial_state.npz'),
            trajectory_sha256=sha(self.folder / 'trajectory.npz'),
            verdict_sha256=sha(self.folder / 'independent_verification.json'),
            public_result_sha256=sha(self.output / 'public_result.json'))
        self.robot.kernel.close()
        write_new(self.output / 'result.json', result)
        return public_result
